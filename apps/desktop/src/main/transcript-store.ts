import { readTextFile, removeStoredFile, writeTextAtomic } from './storage'
import path from 'node:path'

/**
 * The Prophey engine's own transcript storage.
 *
 * One JSONL file per session: a header line, then one line per message. It is deliberately plain —
 * the engine appends what it produced, and reading it back is enough to resume a conversation. pi's
 * session files stay untouched; this is what "our own sessions" means for our own engine.
 */
export interface StoredTranscript {
  sessionId: string
  workspace: { primary: string; additional: string[] }
  messages: Array<Record<string, unknown>>
}

export class TranscriptStore {
  constructor(private readonly dir: string) {}

  /** Absolute path of a session's file; the app treats it as the session's identity. */
  pathFor(sessionId: string): string {
    return this.fileFor(sessionId)
  }

  private fileFor(sessionId: string): string {
    // Ids are generated by us (`s_<hex>`), but a stray path separator must never escape the folder.
    return path.join(this.dir, `${sessionId.replace(/[^a-zA-Z0-9_-]/g, '_')}.jsonl`)
  }

  async remove(sessionId: string): Promise<void> {
    await removeStoredFile(this.fileFor(sessionId))
  }

  async load(sessionId: string): Promise<StoredTranscript | undefined> {
    let raw: string
    try {
      raw = await readTextFile(this.fileFor(sessionId))
    } catch {
      return undefined
    }
    const lines = raw.split('\n').filter((line) => line.trim())
    let header: { sessionId?: string; workspace?: { primary: string; additional: string[] } } = {}
    const messages: Array<Record<string, unknown>> = []
    for (const [index, line] of lines.entries()) {
      let parsed: Record<string, unknown>
      try {
        parsed = JSON.parse(line) as Record<string, unknown>
      } catch {
        // A half-written last line (crash) must not lose the rest of the conversation.
        continue
      }
      if (index === 0 && parsed.type === 'header') {
        header = parsed as typeof header
        continue
      }
      if (parsed.message && typeof parsed.message === 'object') {
        messages.push(parsed.message as Record<string, unknown>)
      }
    }
    return {
      sessionId,
      workspace: header.workspace ?? { primary: '', additional: [] },
      messages
    }
  }

  /** Snapshot and serialize full rewrites, so concurrent saves cannot interleave. */
  async save(
    sessionId: string,
    workspace: { primary: string; additional: string[] },
    messages: Array<Record<string, unknown>>,
    strict = false
  ): Promise<void> {
    const body = [
      JSON.stringify({ type: 'header', sessionId, workspace, savedAt: Date.now() }),
      ...messages.map((message) => JSON.stringify({ message }))
    ].join('\n')
    try {
      await writeTextAtomic(this.fileFor(sessionId), `${body}\n`)
    } catch (error) {
      if (strict) throw error
      // Losing persistence is bad, losing the conversation in memory is worse: stay quiet here.
    }
  }
}
